#!/bin/sh
# Generates src/preview/ui_assets.cpp from src/preview/ui/*. POSIX sh only.
set -eu
cd "$(dirname "$0")/.."
for f in index.html app.js app.css; do
    if grep -q ')AHPVUI"' "src/preview/ui/$f"; then
        echo "embed_ui.sh: delimiter collision in $f" >&2
        exit 1
    fi
done
emit() {
    printf 'const std::string& %s() {\n    static const std::string text = R"AHPVUI(' "$1"
    cat "src/preview/ui/$2"
    printf ')AHPVUI";\n    return text;\n}\n\n'
}
{
    printf '// GENERATED by scripts/embed_ui.sh from src/preview/ui/. Do not edit.\n'
    printf '#include "preview/ui_assets.hpp"\n\nnamespace ahpv {\n\n'
    emit ui_index_html index.html
    emit ui_app_js app.js
    emit ui_app_css app.css
    printf '}  // namespace ahpv\n'
} > src/preview/ui_assets.cpp.tmp
mv src/preview/ui_assets.cpp.tmp src/preview/ui_assets.cpp
